def make_handler(config_path: Path, output: Path) -> type[BaseHTTPRequestHandler]:
    """Create a request handler bound to one editor configuration."""

    class Handler(BaseHTTPRequestHandler):
        def _json(self, data: dict[str, Any], status: HTTPStatus = HTTPStatus.OK) -> None:
            body = json.dumps(data, ensure_ascii=False).encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def do_GET(self) -> None:  # noqa: N802
            if self.path == "/config":
                self._json(load_editor_config(config_path))
                return
            if self.path not in {"/", "/index.html"}:
                self.send_error(HTTPStatus.NOT_FOUND)
                return
            body = HTML.encode("utf-8")
            self.send_response(HTTPStatus.OK)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def do_POST(self) -> None:  # noqa: N802
            if self.path != "/save":
                self.send_error(HTTPStatus.NOT_FOUND)
                return
            try:
                length = min(int(self.headers.get("Content-Length", "0")), 65536)
                payload = json.loads(self.rfile.read(length).decode("utf-8"))
                waypoints = validate_waypoints(payload.get("waypoints"))
                current_config = load_editor_config(config_path)
                save_route(output, current_config["start"], waypoints)
                self._json({"ok": True, "path": str(output), "waypoints": waypoints})
            except (ValueError, TypeError, json.JSONDecodeError) as exc:
                self._json({"ok": False, "error": str(exc)}, HTTPStatus.BAD_REQUEST)

        def log_message(self, format_string: str, *args: Any) -> None:
            print(f"[route-editor] {format_string % args}")

    return Handler


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--host", default="0.0.0.0")
    parser.add_argument("--port", type=int, default=8767)
    parser.add_argument("--no-browser", action="store_true")
    args = parser.parse_args()

    config_path = args.config.resolve()
    # Fail early with a clear error before binding the server port.
    load_editor_config(config_path)
    output = args.output.resolve()
    server = ThreadingHTTPServer((args.host, args.port), make_handler(config_path, output))
    local_url = f"http://127.0.0.1:{args.port}/"
    print(f"Waypoint route editor: {local_url}")
    print(f"Saved route overlay: {output}")
    print("Stop with Ctrl-C.")
    if not args.no_browser:
        threading.Timer(0.4, lambda: webbrowser.open(local_url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
