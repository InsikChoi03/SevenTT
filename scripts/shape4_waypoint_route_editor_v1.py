FIELD_BOUNDS = (-2.0, 2.0, -2.0, 2.0)
SNAP_M = 0.25


def _node_params(data: dict[str, Any], node_name: str) -> dict[str, Any]:
    node = data.get(node_name, {})
    params = node.get("ros__parameters", {}) if isinstance(node, dict) else {}
    return params if isinstance(params, dict) else {}


def _pairs(values: Any) -> list[list[float]]:
    if not isinstance(values, list):
        return []
    numbers = [float(value) for value in values]
    return [[numbers[i], numbers[i + 1]] for i in range(0, len(numbers) - 1, 2)]


def load_editor_config(path: Path) -> dict[str, Any]:
    """Load the current route and object-grid geometry from the tuning YAML."""
    with path.open(encoding="utf-8") as stream:
        data = yaml.safe_load(stream) or {}
    mission = _node_params(data, "mission_fsm_node")
    viz = _node_params(data, "recognition_viz_node")
    rows = int(viz.get("grid_rows", 6))
    cols = int(viz.get("grid_cols", 7))
    spacing = float(viz.get("grid_spacing_m", 0.5))
    origin_x = float(viz.get("grid_origin_x_m", -1.5))
    origin_y = float(viz.get("grid_origin_y_m", -1.0))
    object_points = [
        [origin_x + col * spacing, origin_y + row * spacing]
        for row in range(rows)
        for col in range(cols)
    ]
    start = mission.get("global_zigzag_start_xy", [-1.8, 1.8])
    if not isinstance(start, list) or len(start) < 2:
        start = [-1.8, 1.8]
    return {
        "field_bounds": list(FIELD_BOUNDS),
        "snap_m": SNAP_M,
        "object_points": object_points,
        "object_grid": {
            "rows": rows,
            "cols": cols,
            "spacing_m": spacing,
            "y_min": origin_y,
            "y_max": origin_y + max(0, rows - 1) * spacing,
        },
        "start": [float(start[0]), float(start[1])],
        "current_route": _pairs(mission.get("global_zigzag_waypoints_xy", [])),
        "source_config": str(path),
    }


def validate_waypoints(payload: Any) -> list[list[float]]:
    """Validate, clamp and quarter-grid-snap route points received from the browser."""
    if not isinstance(payload, list) or len(payload) > 200:
        raise ValueError("waypoints must be a list with at most 200 points")
    xmin, xmax, ymin, ymax = FIELD_BOUNDS
    result: list[list[float]] = []
    for point in payload:
        if not isinstance(point, list) or len(point) != 2:
            raise ValueError("every waypoint must be [x, y]")
        x, y = float(point[0]), float(point[1])
        if not math.isfinite(x) or not math.isfinite(y):
            raise ValueError("waypoint coordinates must be finite")
        x = min(xmax, max(xmin, round(x / SNAP_M) * SNAP_M))
        y = min(ymax, max(ymin, round(y / SNAP_M) * SNAP_M))
        snapped = [round(x, 2), round(y, 2)]
        if not result or snapped != result[-1]:
            result.append(snapped)
    return result


def save_route(path: Path, start: list[float], waypoints: list[list[float]]) -> None:
    """Write a small ROS parameter overlay that can be copied into motion tuning."""
    flat = [coordinate for point in waypoints for coordinate in point]
    overlay = {
        "mission_fsm_node": {
            "ros__parameters": {
                "global_zigzag_start_xy": start,
                "global_zigzag_waypoints_xy": flat,
            }
        },
        "recognition_viz_node": {
            "ros__parameters": {
                "global_zigzag_start_xy": list(start),
                "global_zigzag_waypoints_xy": list(flat),
            }
        },
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as stream:
        stream.write("# Generated by shape4_waypoint_route_editor_v1.py\n")
        yaml.safe_dump(overlay, stream, sort_keys=False, allow_unicode=True)


